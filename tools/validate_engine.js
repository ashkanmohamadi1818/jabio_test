// node tools/validate_engine.js [--write]
// Does the engine put a business where businesses of that kind already are?
//
// Method ("revealed preference"): for every real business of a type in OpenStreetMap, take its 250 m cell and ask how that
// cell scores. Compare with every other built-up cell that has no such business. AUC = the chance that a cell with a real
// business scores higher than a cell without one: 0.5 is no better than chance, 1.0 is perfect.
// To keep it honest the score is computed BLIND: the business's own category is removed from every input, and each
// business is removed from its own competition count (leave-one-out). Otherwise the engine would simply find itself.
//
// What this is NOT: it does not prove a place is profitable. Existing businesses are where owners chose to open (and
// they include failures), OSM is incomplete, and clustering is attractive for many trades. It measures whether the
// engine's picture of "a good place" agrees with what the market already shows.
const fs = require('fs'), path = require('path');
const { J, cities, load, auc, samples, root } = require('./validation_lib.js');
const WRITE = process.argv.includes('--write');
const R = +(process.env.RADIUS || 1000), MINPOS = 30;

const rows = [];
for (const cm of cities) {
  const C = load(cm.id);
  for (const type of J.ORDER) {
    const S = samples(C, type, R, MINPOS);
    if (!S) { rows.push({ city: cm.id, type, skipped: true }); continue; }
    const t = S.W, sc = f => t.pop * f.pop + t.demand * f.demand + t.access * f.access + t.comp * f.room;
    const r = { city: cm.id, cov: C.coverage, type, n: S.pos.length, cells: S.neg.length };
    ['pop', 'demand', 'access', 'lowcomp', 'room', 'comp'].forEach(k => { r[k] = auc(S.pos.map(f => f[k]), S.neg.map(f => f[k])); });
    r.score = auc(S.pos.map(sc), S.neg.map(sc));
    rows.push(r);
  }
}

const used = rows.filter(r => !r.skipped);
const wmean = (rs, k) => rs.reduce((s, r) => s + r[k] * r.n, 0) / rs.reduce((s, r) => s + r.n, 0);
const f = v => v.toFixed(2);
let out = [];
out.push('| Business | Places tested | Whole score | Population | Demand | Access | Few rivals (raw) | Room vs demand | Rivals nearby |');
out.push('|---|---|---|---|---|---|---|---|---|');
const perType = {};
J.ORDER.forEach(t => {
  const rs = used.filter(r => r.type === t); if (!rs.length) { out.push('| ' + t + ' | too few | | | | | | | |'); return; }
  perType[t] = { n: rs.reduce((s, r) => s + r.n, 0), cities: rs.length };
  ['score', 'pop', 'demand', 'access', 'lowcomp', 'room', 'comp'].forEach(k => perType[t][k] = wmean(rs, k));
  const p = perType[t];
  out.push('| ' + t + ' | ' + p.n + ' (' + p.cities + ' cities) | ' + f(p.score) + ' | ' + f(p.pop) + ' | ' + f(p.demand) + ' | ' + f(p.access) + ' | ' + f(p.lowcomp) + ' | ' + f(p.room) + ' | ' + f(p.comp) + ' |');
});
const all = { score: wmean(used, 'score'), pop: wmean(used, 'pop'), demand: wmean(used, 'demand'), access: wmean(used, 'access'), lowcomp: wmean(used, 'lowcomp'), room: wmean(used, 'room') };
console.log('Radius ' + R + ' m, ' + used.length + ' city x business tests, ' + used.reduce((s, r) => s + r.n, 0) + ' real places');
console.log(out.join('\n'));
console.log('\nAll tests, weighted by places:', JSON.stringify(Object.fromEntries(Object.entries(all).map(([k, v]) => [k, +v.toFixed(3)]))));
const share = used.filter(r => r.score > .5).length / used.length;
console.log('Tests where the whole score beats chance: ' + Math.round(share * 100) + '%');
const byCov = {}; used.forEach(r => (byCov[r.cov] = byCov[r.cov] || []).push(r));
Object.keys(byCov).forEach(k => console.log('  coverage ' + k + ': whole-score AUC ' + f(wmean(byCov[k], 'score')) + ' over ' + byCov[k].length + ' tests'));
if (WRITE) {
  fs.writeFileSync(path.join(root, 'tools', 'validation.json'), JSON.stringify({ radius: R, method: J.METHOD, perType, all, rows: used.map(r => Object.assign({}, r, { pop: +r.pop.toFixed(3), demand: +r.demand.toFixed(3), access: +r.access.toFixed(3), lowcomp: +r.lowcomp.toFixed(3), comp: +r.comp.toFixed(3), score: +r.score.toFixed(3) })) }, null, 1));
  const md = ['# Engine validation (method ' + J.METHOD + ', radius ' + R + ' m)', '',
    'Generated by `node tools/validate_engine.js --write`. Do not edit by hand.', '',
    '**Question:** does the engine give a high score to the places where businesses of that kind already operate?',
    '', '**How:** for each of ' + used.reduce((s, r) => s + r.n, 0).toLocaleString('en') + ' real places in OpenStreetMap, take its 250 m cell and compare its score with every built-up cell that has no such place. The number is AUC: the chance a cell with a real place scores higher than one without. 0.50 = chance, 1.00 = perfect. The score is computed blind: the business\'s own category is removed from every input and each place is removed from its own rival count.',
    '', out.join('\n'), '',
    'All tests together (weighted by places): whole score **' + f(all.score) + '**, population ' + f(all.pop) + ', demand ' + f(all.demand) + ', access ' + f(all.access) + ', few rivals (raw count) ' + f(all.lowcomp) + ', room against demand ' + f(all.room) + '.',
    '', '## What it shows', '',
    '- Demand and access agree strongly with where businesses are (about 0.8). Population agrees well (about 0.7).',
    '- A bare "few rivals" count points the opposite way (about ' + f(all.lowcomp) + '): businesses cluster where demand is. That is why the engine does not use it. It uses "room": the rivals present against the number the local demand normally carries (50 = as many as usual). Room scores ' + f(all.room) + ' on its own and lifts the whole score to ' + f(all.score) + '.',
    '- Results hold in cities with rich, partial and thin OpenStreetMap coverage.', '',
    '## What it does not show', '',
    '- It does not show that a place is profitable. Existing businesses include ones that failed, and owners also choose busy streets because rent is high there.',
    '- Clustering being common does not prove that rivals are harmless to a newcomer. It means "no rivals" is not a reliable sign of a good place, and the competition term should be read as saturation against demand, not as a bare count.',
    '- OpenStreetMap is incomplete; a missing place counts as an empty cell.',
    '- Real sales, closures and rent are not in the data, so this cannot be turned into a profit forecast.'].join('\n') + '\n';
  fs.writeFileSync(path.join(root, 'VALIDATION.md'), md);
  console.log('wrote tools/validation.json and VALIDATION.md');
}
